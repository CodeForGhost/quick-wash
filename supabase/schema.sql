-- Views
-- ============================================================================
-- PostgREST has no GROUP BY and no correlated subquery, and the dashboards ask
-- for both. security_invoker means these run as the caller, so the row level
-- security on the underlying tables still applies through them.

/** FR-025: how much work each agent is currently carrying. */
create or replace view agent_workload
with (security_invoker = on) as
  select u.*,
         (select count(*) from public.laundry_orders o
           where o.pickup_agent_id = u.id and o.status = 'PICKUP_ASSIGNED')    as active_pickups,
         (select count(*) from public.laundry_orders o
           where o.delivery_agent_id = u.id and o.status = 'OUT_FOR_DELIVERY') as active_deliveries,
         (select count(*) from public.laundry_orders o
           where o.delivery_agent_id = u.id and o.status = 'DELIVERED')        as completed
    from public.users u
   where u.role = 'PICKUP_AGENT';

/** FR-024: customers with their order totals. */
create or replace view customer_summary
with (security_invoker = on) as
  select u.*,
         (select count(*) from public.laundry_orders o where o.customer_id = u.id) as order_count,
         (select sum(o.price) from public.laundry_orders o
           where o.customer_id = u.id and o.status = 'DELIVERED')                  as total_spend,
         (select max(o.created_at) from public.laundry_orders o
           where o.customer_id = u.id)                                             as last_order_at
    from public.users u
   where u.role = 'CUSTOMER';

/**
 * FR-023: the board, one row per status. statusCounts() used to select every
 * order's status column and count the rows in JavaScript - the whole table
 * over the wire, on a dashboard that asks for it twice.
 */
create or replace view order_status_counts
with (security_invoker = on) as
  select status, count(*)::integer as total
    from public.laundry_orders
   group by status;

/** The same, for the "today" panel: one row per status per pickup date. */
create or replace view order_status_counts_by_date
with (security_invoker = on) as
  select pickup_date, status, count(*)::integer as total
    from public.laundry_orders
   group by pickup_date, status;


