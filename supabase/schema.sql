-- QuickWash on Supabase: Postgres, Auth and row level security (SRS section 10).
-- Run once in Supabase -> SQL Editor. Safe to re-run: it drops first.
--
-- Sign-in is by mobile number. Supabase Auth is email-based, so a synthetic
-- address (0771111111@quickwash.local) carries the phone as the credential;
-- nobody ever sees or types it. public.users.auth_id is the link.

