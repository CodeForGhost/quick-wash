-- Users ----------------------------------------------------------------------
-- You always see yourself. Staff see the people they work with: an admin sees
-- everyone, an agent and the shop see the customers on their own orders.
create policy "users read themselves and their counterparts" on users
  for select using (
    auth_id = auth.uid()
    or public.is_admin()
    -- Anyone named on an order you are allowed to see. Symmetric on purpose:
    -- the customer needs the agent's number as much as the agent needs theirs.
    -- Inlined rather than calling can_view_order() so this is one scan, not
    -- one definer call per row.
    or exists (
      select 1 from public.laundry_orders o
       where users.id in (o.customer_id, o.pickup_agent_id, o.delivery_agent_id)
         and case public.my_role()
               when 'CUSTOMER'     then o.customer_id = public.me()
               when 'PICKUP_AGENT' then o.pickup_agent_id = public.me()
                                      or o.delivery_agent_id = public.me()
               when 'SHOP_STAFF'   then public.my_shop() is null
                                      or o.laundry_shop_id = public.my_shop()
                                      or o.laundry_shop_id is null
               else false
             end
    )
  );

create policy "you edit your own profile" on users
  for update using (auth_id = auth.uid()) with check (auth_id = auth.uid());

create policy "admins manage accounts" on users
  for all using (public.is_admin()) with check (public.is_admin());

-- Addresses ------------------------------------------------------------------
create policy "your own address book" on addresses
  for select using (
    user_id = public.me()
    or public.is_admin()
    -- The agent at the door needs the address of the order they are collecting.
    or exists (
      select 1 from public.laundry_orders o
       where o.pickup_address_id = addresses.id and public.can_view_order(o.id)
    )
  );

create policy "you manage your own addresses" on addresses
  for all using (user_id = public.me() or public.is_admin())
  with check (user_id = public.me() or public.is_admin());

-- Laundry shops --------------------------------------------------------------
create policy "shops are readable by anyone signed in" on laundry_shops
  for select using (public.me() is not null);

create policy "admins manage shops" on laundry_shops
  for all using (public.is_admin()) with check (public.is_admin());

-- Orders ---------------------------------------------------------------------
-- BR-008. Writes go through the functions above, which is why there is no
-- insert or update policy here: only an admin may touch a row directly.
create policy "orders follow BR-008" on laundry_orders
  for select using (public.can_view_order(id));

create policy "admins edit orders directly" on laundry_orders
  for all using (public.is_admin()) with check (public.is_admin());

