                     order_counters, settings cascade;

-- 10.5 Laundry shops ---------------------------------------------------------
-- First: users.shop_id references it, and Postgres has no forward FKs.
create table laundry_shops (
  id          bigint generated by default as identity primary key,
  name        text not null,
  phone       text,
  address     text,
  latitude    double precision,
  longitude   double precision,
  is_active   boolean     not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- 10.1 Users -----------------------------------------------------------------
create table users (
  id         bigint generated by default as identity primary key,
  auth_id    uuid unique references auth.users (id) on delete cascade,
  name       text not null,
  phone      text not null unique,
  email      text,
  role       text not null check (role in ('CUSTOMER','PICKUP_AGENT','SHOP_STAFF','ADMIN')),
  shop_id    bigint references laundry_shops (id) on delete set null,
  is_active  boolean     not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index idx_users_role on users (role);
create index idx_users_auth on users (auth_id);

-- 10.2 Addresses -------------------------------------------------------------
create table addresses (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references users (id) on delete cascade,
  label      text not null,
  address    text not null,
  area       text,
  landmark   text,
  latitude   double precision,
  longitude  double precision,
  phone      text,
  is_deleted boolean     not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index idx_addresses_user on addresses (user_id);

-- 10.3 Laundry orders --------------------------------------------------------
create table laundry_orders (
  id                bigint generated by default as identity primary key,
  order_number      text not null unique,
  customer_id       bigint not null references users (id) on delete restrict,
  pickup_agent_id   bigint references users (id) on delete set null,
  delivery_agent_id bigint references users (id) on delete set null,
  laundry_shop_id   bigint references laundry_shops (id) on delete set null,
  status            text not null default 'PENDING',
  pickup_address_id bigint not null references addresses (id) on delete restrict,
  pickup_date       date not null,
  pickup_time_slot  text not null,
  bag_count         integer not null,
  item_count        integer,
  actual_bag_count  integer,
  price             numeric(10,2),
  notes             text,
  picked_up_at      timestamptz,
  received_at       timestamptz,
  ready_at          timestamptz,
  delivered_at      timestamptz,
  cancelled_at      timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index idx_orders_customer on laundry_orders (customer_id);
create index idx_orders_status   on laundry_orders (status);
create index idx_orders_pickup   on laundry_orders (pickup_agent_id);
create index idx_orders_delivery on laundry_orders (delivery_agent_id);
create index idx_orders_date     on laundry_orders (pickup_date);

